/**
 * Local persistence API for the Video Notes app.
 *
 * A zero-dependency Node server that stores the app data as JSON files
 * in the "notes" folder next to this file (video-notes.json, user.json),
 * so data survives page reloads without any browser folder-picker.
 *
 * Endpoints:
 *   GET  /api/notes  -> current video notes dataset (JSON, [] when empty)
 *   PUT  /api/notes  -> replaces the dataset with the request body (JSON)
 *   GET  /api/user   -> saved user name (plain text, '' when empty)
 *   PUT  /api/user   -> replaces the user name with the request body (text)
 *   GET  /api/theme  -> saved color theme id (plain text, '' when empty)
 *   PUT  /api/theme  -> replaces the color theme id with the request body (text)
 *   GET  /api/projects           -> [{ id, name, updatedAt }] project index
 *   GET  /api/projects?list=1    -> ["<id>", ...] ids found in notes/projects
 *   GET  /api/projects/<id>      -> one project as JSON (404 when missing)
 *   PUT  /api/projects/<id>      -> writes notes/projects/<id>.json
 *   DELETE /api/projects/<id>    -> deletes notes/projects/<id>.json
 *
 * Run with: node server.js  (or `npm start`, which starts it together with ng serve)
 */
const http = require('http');
const fs = require('fs');
const path = require('path');

const PORT = Number(process.env.API_PORT) || 3000;
const DATA_DIR = path.join(__dirname, 'notes');
const NOTES_FILE = path.join(DATA_DIR, 'video-notes.json');
const USER_FILE = path.join(DATA_DIR, 'user.json');
const THEME_FILE = path.join(DATA_DIR, 'theme.json');
const PROJECTS_DIR = path.join(DATA_DIR, 'projects');
const MAX_BODY_BYTES = 20 * 1024 * 1024; // 20 MB safety limit
/** Ids are generated by the app; keep them file-system safe. */
const PROJECT_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;

function send(res, status, body, contentType) {
  res.writeHead(status, {
    'Content-Type': contentType || 'text/plain; charset=utf-8',
    'Cache-Control': 'no-store'
  });
  res.end(body);
}

function sendJson(res, status, value) {
  send(res, status, JSON.stringify(value), 'application/json; charset=utf-8');
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    let size = 0;
    const chunks = [];
    req.on('data', chunk => {
      size += chunk.length;
      if (size > MAX_BODY_BYTES) {
        reject(new Error('Request body too large'));
        req.destroy();
        return;
      }
      chunks.push(chunk);
    });
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

// Pretty-prints the notes dataset so every day entry sits on its own
// line, keeping the file readable in an editor. Each year and month is
// also broken onto its own block; only the day (and its videos) stays
// compact on a single line.
function formatNotesFile(years) {
  if (!Array.isArray(years) || years.length === 0) {
    return JSON.stringify(years, null, 2);
  }
  const yearBlocks = years.map(year => {
    const months = Array.isArray(year.months) ? year.months : [];
    const yearFields = Object.entries(year)
      .filter(([key]) => key !== 'months')
      .map(([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)}`)
      .join(',\n');
    const monthBlocks = months.map(month => {
      const days = Array.isArray(month.days) ? month.days : [];
      const monthFields = Object.entries(month)
        .filter(([key]) => key !== 'days')
        .map(([key, value]) => `        ${JSON.stringify(key)}: ${JSON.stringify(value)}`)
        .join(',\n');
      const dayLines = days.map(day => `          ${JSON.stringify(day)}`).join(',\n');
      const daysBlock = days.length === 0 ? '[]' : `[\n${dayLines}\n        ]`;
      const monthBody = [monthFields, `        "days": ${daysBlock}`].filter(Boolean).join(',\n');
      return `      {\n${monthBody}\n      }`;
    });
    const monthsBlock = monthBlocks.length === 0 ? '[]' : `[\n${monthBlocks.join(',\n')}\n    ]`;
    const yearBody = [yearFields, `    "months": ${monthsBlock}`].filter(Boolean).join(',\n');
    return `  {\n${yearBody}\n  }`;
  });
  return `[\n${yearBlocks.join(',\n')}\n]`;
}

/**
 * Normalizes a URL typed by the user: adds https:// when the scheme is
 * missing. Returns null for empty input.
 * (Mirrors normalizeUrl in src/app/project-notes/models/project-note.model.ts)
 */
function normalizeUrl(value) {
  const trimmed = String(value || '').trim();
  if (!trimmed) return null;
  if (/^[a-z][a-z0-9+.-]*:/i.test(trimmed)) return trimmed;
  return 'https://' + trimmed;
}

/** Pretty JSON with one link/image per line, so project files stay readable. */
function formatProjectFile(project) {
  const pretty = JSON.stringify(project, null, 2);
  return pretty.replace(/\[(?:[^\[\]{}]|\{[^{}]*\})*\]/g, (match, offset, whole) => {
    const keyContext = whole.slice(Math.max(0, offset - 60), offset);
    if (!/"(links|images)"\s*:\s*$/.test(keyContext)) return match;
    const items = JSON.parse(match);
    if (!Array.isArray(items) || items.length === 0) return match;
    const lineIndent = whole.slice(0, offset).split('\n').pop().length - 1;
    const pad = ' '.repeat(lineIndent);
    const body = items.map(item => pad + '    ' + JSON.stringify(item)).join(',\n');
    return `[\n${body}\n${pad}  ]`;
  }) + '\n';
}

// Atomic write: write to a temp file first, then rename over the target.
function writeFileAtomic(filePath, contents) {
  const tempPath = `${filePath}.tmp`;
  fs.writeFileSync(tempPath, contents, 'utf8');
  fs.renameSync(tempPath, filePath);
}

/** Rolling snapshots of the notes dataset, kept next to the data file. */
const BACKUP_DIR = path.join(DATA_DIR, 'backups');
const MAX_BACKUPS = 50;

/**
 * Copies the current data file into notes/backups/ before it is replaced.
 *
 * Replaces are whole-file, so a bad request body can wipe every saved video
 * in one write. Keeping a rolling copy means the previous state is always
 * one file away instead of gone.
 */
function backupFile(filePath) {
  try {
    if (!fs.existsSync(filePath)) return;
    const contents = fs.readFileSync(filePath);
    // Nothing worth preserving in an empty dataset.
    if (contents.length <= 3) return;
    fs.mkdirSync(BACKUP_DIR, { recursive: true });
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    const name = path.basename(filePath, '.json');
    fs.writeFileSync(path.join(BACKUP_DIR, `${name}.${stamp}.json`), contents);
    pruneBackups(name);
  } catch (err) {
    console.error('[api] could not write backup:', err.message);
  }
}

/** Keeps the most recent MAX_BACKUPS snapshots for one data file. */
function pruneBackups(name) {
  try {
    const files = fs.readdirSync(BACKUP_DIR)
      .filter(file => file.startsWith(`${name}.`) && file.endsWith('.json'))
      .sort();
    for (const file of files.slice(0, Math.max(0, files.length - MAX_BACKUPS))) {
      fs.unlinkSync(path.join(BACKUP_DIR, file));
    }
  } catch {
    // Pruning is best-effort; a leftover snapshot never harms the data.
  }
}

/** Number of saved video entries in a parsed notes dataset. */
function countVideos(years) {
  if (!Array.isArray(years)) return 0;
  let count = 0;
  for (const year of years) {
    for (const month of year?.months ?? []) {
      for (const day of month?.days ?? []) {
        count += Array.isArray(day?.videos) ? day.videos.length : 0;
      }
    }
  }
  return count;
}

/**
 * True when a write would replace saved videos with an empty dataset.
 *
 * Every save sends the whole dataset, so one bad read (an unparsed response,
 * a client bug) is enough to erase the file. An overwrite that drops every
 * video is refused unless the client explicitly passes ?force=1.
 */
function isDestructiveWrite(filePath, parsed) {
  if (countVideos(parsed) > 0) return false;
  try {
    const existing = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    return countVideos(existing) > 0;
  } catch {
    // Missing or unreadable file: nothing to protect.
    return false;
  }
}

function readDataFile(filePath, fallback) {
  try {
    return fs.readFileSync(filePath, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') return fallback;
    throw err;
  }
}

async function handle(req, res) {
  const [pathPart, queryPart] = (req.url || '').split('?');
  const url = pathPart;
  const searchParams = new URLSearchParams(queryPart || '');

  if (url === '/api/notes') {
    if (req.method === 'GET') {
      send(res, 200, readDataFile(NOTES_FILE, '[]'), 'application/json; charset=utf-8');
      return;
    }
    if (req.method === 'PUT') {
      const body = await readBody(req);
      let parsed;
      try {
        parsed = JSON.parse(body); // validate before writing
      } catch {
        sendJson(res, 400, { error: 'Body is not valid JSON' });
        return;
      }
      // Refuse to wipe every saved video unless the caller insists.
      if (searchParams.get('force') !== '1' && isDestructiveWrite(NOTES_FILE, parsed)) {
        console.warn('[api] blocked a write that would erase all saved videos');
        sendJson(res, 409, {
          error: 'Refusing to replace saved videos with an empty dataset',
          hint: 'Send the full dataset, or repeat the request with ?force=1 to erase it on purpose'
        });
        return;
      }
      backupFile(NOTES_FILE);
      writeFileAtomic(NOTES_FILE, formatNotesFile(parsed) + '\n');
      sendJson(res, 200, { ok: true, bytes: Buffer.byteLength(body) });
      return;
    }
  }

  if (url === '/api/user') {
    if (req.method === 'GET') {
      send(res, 200, readDataFile(USER_FILE, ''), 'text/plain; charset=utf-8');
      return;
    }
    if (req.method === 'PUT') {
      const body = await readBody(req);
      writeFileAtomic(USER_FILE, body);
      sendJson(res, 200, { ok: true });
      return;
    }
  }

  if (url === '/api/theme') {
    if (req.method === 'GET') {
      send(res, 200, readDataFile(THEME_FILE, ''), 'text/plain; charset=utf-8');
      return;
    }
    if (req.method === 'PUT') {
      const body = await readBody(req);
      writeFileAtomic(THEME_FILE, body);
      sendJson(res, 200, { ok: true });
      return;
    }
  }

  if (url === '/api/projects' || url.startsWith('/api/projects/')) {
    if (await handleProjects(req, res, url, searchParams)) return;
  }

  sendJson(res, 404, { error: 'Not found' });
}

/** Index file listing every project; the folder itself is the source of truth. */
function projectIndex() {
  let names = [];
  try {
    names = fs.readdirSync(PROJECTS_DIR);
  } catch {
    return [];
  }
  return names
    .filter(name => name.endsWith('.json') && name !== 'index.json')
    .map(name => {
      const id = name.slice(0, -'.json'.length);
      let name_ = id;
      let updatedAt = '';
      try {
        const project = JSON.parse(fs.readFileSync(path.join(PROJECTS_DIR, name), 'utf8'));
        if (project && typeof project.name === 'string') name_ = project.name;
        if (project && typeof project.updatedAt === 'string') updatedAt = project.updatedAt;
      } catch {
        // Unreadable file: still listed so the user can fix or delete it.
      }
      return { id, name: name_, updatedAt };
    })
    .sort((a, b) => (b.updatedAt || '').localeCompare(a.updatedAt || ''));
}

/** Returns true when the request was handled here. */
async function handleProjects(req, res, url, searchParams) {
  if (url === '/api/projects') {
    if (req.method === 'GET') {
      if (searchParams.get('list') === '1') {
        sendJson(res, 200, projectIndex().map(entry => entry.id));
      } else {
        sendJson(res, 200, { projects: projectIndex() });
      }
      return true;
    }
    return false;
  }

  const id = decodeURIComponent(url.slice('/api/projects/'.length));
  if (id === 'index.json') {
    if (req.method === 'GET') {
      const raw = readDataFile(path.join(PROJECTS_DIR, 'index.json'), null);
      send(res, 200, raw ?? JSON.stringify({ projects: projectIndex() }), 'application/json; charset=utf-8');
      return true;
    }
    if (req.method === 'PUT') {
      const body = await readBody(req);
      try {
        JSON.parse(body);
      } catch {
        sendJson(res, 400, { error: 'Body is not valid JSON' });
        return true;
      }
      writeFileAtomic(path.join(PROJECTS_DIR, 'index.json'), body);
      sendJson(res, 200, { ok: true });
      return true;
    }
    if (req.method === 'DELETE') {
      // The index is derived from the folder, so deleting it is a no-op.
      sendJson(res, 200, { ok: true });
      return true;
    }
    return false;
  }

  if (!PROJECT_ID_PATTERN.test(id)) {
    sendJson(res, 400, { error: 'Invalid project id' });
    return true;
  }
  const filePath = path.join(PROJECTS_DIR, `${id}.json`);

  if (req.method === 'GET') {
    const raw = readDataFile(filePath, null);
    if (raw === null) {
      sendJson(res, 404, { error: 'Project not found' });
      return true;
    }
    send(res, 200, raw, 'application/json; charset=utf-8');
    return true;
  }

  if (req.method === 'PUT') {
    const body = await readBody(req);
    let parsed;
    try {
      parsed = JSON.parse(body);
    } catch {
      sendJson(res, 400, { error: 'Body is not valid JSON' });
      return true;
    }
    if (!parsed || parsed.id !== id) {
      sendJson(res, 400, { error: 'Project id does not match the URL' });
      return true;
    }
    backupFile(filePath);
    writeFileAtomic(filePath, formatProjectFile(parsed));
    sendJson(res, 200, { ok: true, bytes: Buffer.byteLength(body) });
    return true;
  }

  if (req.method === 'DELETE') {
    try {
      fs.unlinkSync(filePath);
      sendJson(res, 200, { ok: true });
    } catch (err) {
      if (err.code === 'ENOENT') {
        sendJson(res, 200, { ok: true, deleted: false });
      } else {
        throw err;
      }
    }
    return true;
  }

  return false;
}

fs.mkdirSync(DATA_DIR, { recursive: true });
fs.mkdirSync(PROJECTS_DIR, { recursive: true });

const server = http.createServer((req, res) => {
  handle(req, res).catch(err => {
    console.error('[api] error handling', req.method, req.url, err);
    if (!res.headersSent) sendJson(res, 500, { error: String(err && err.message || err) });
  });
});

server.listen(PORT, () => {
  console.log(`[api] Video Notes persistence API listening on http://localhost:${PORT}`);
  console.log(`[api] Data folder: ${DATA_DIR}`);
});
